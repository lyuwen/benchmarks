"""Regression tests for the loss-mask assignment in the trajectory flattener."""

import json

import extract_trajectories_jsonl as extract


def _message(role, content, **extra):
    return {"role": role, "content": content, **extra}


def _copy(messages):
    # Real input is parsed from JSON, so each view owns independent dicts; the
    # flattener mutates its input, so fixtures must not alias across views.
    return [dict(message) for message in messages]


def _summary(content="summary"):
    return _message("assistant", content)


def _trajectory_entry(messages):
    return {"type": "trajectory", "messages": _copy(messages)}


def _compaction_entry(request, response):
    return {"type": "compaction", "request": _copy(request), "response": dict(response)}


def _history(messages, trajectories):
    return {
        "instance_id": "instance",
        "messages": messages,
        "tools": [],
        "trajectories": trajectories,
    }


def _rows_by_index(history):
    rows = extract.extract_trajectory_rows(history)
    return {json.loads(row["metadata"])["trajectory_index"]: row for row in rows}


def _masks(row):
    return [
        (message["role"], message["content"], message["loss_mask"])
        for message in row["messages"]
    ]


def test_preserved_history_is_not_trained_again_after_compaction():
    system = _message("system", "sys")
    user = _message("user", "task")
    first = _message("assistant", "first")
    feedback = _message("user", "feedback")
    preserved = _message("assistant", "preserved")
    after_compaction = _message("assistant", "after compaction")
    transcript = [system, user, first, feedback, preserved, after_compaction]
    for message in transcript:
        message["loss_mask"] = int(message["role"] == "assistant")

    history = _history(
        [
            system,
            user,
            first,
            feedback,
            preserved,
            _message("context", "summary"),
            after_compaction,
        ],
        [
            # Segment before the compaction: first, feedback and preserved were
            # generated there.
            _trajectory_entry([system, user, first, feedback, preserved]),
            _compaction_entry([system, user, first, feedback], _summary()),
            # Post-compaction segment replays "preserved" as kept history.
            _trajectory_entry(
                [system, user, _message("user", "summary"), preserved, after_compaction]
            ),
        ],
    )

    rows = _rows_by_index(history)
    pre_compaction = [mask for _, _, mask in _masks(rows[0])]
    post_compaction = [mask for _, _, mask in _masks(rows[2])]

    # Everything pre-compaction keeps its own mask; the preserved turn was
    # generated by this segment.
    assert pre_compaction == [0, 0, 1, 0, 1]
    # In the replayed segment only the new turn is trainable: the system prompt,
    # instruction, inserted summary and preserved history are all context.
    assert post_compaction == [0, 0, 0, 0, 1]


def test_replay_is_masked_across_multiple_compactions():
    system = _message("system", "sys")
    user = _message("user", "task")
    first = _message("assistant", "first")
    second = _message("assistant", "second")
    third = _message("assistant", "third")
    transcript = [system, user, first, second, third]
    for message in transcript:
        message["loss_mask"] = int(message["role"] == "assistant")

    history = _history(
        [
            system,
            user,
            first,
            _message("context", "summary one"),
            second,
            _message("context", "summary two"),
            third,
        ],
        [
            _trajectory_entry([system, user, first]),
            _compaction_entry([system, user], _summary("summary one")),
            _trajectory_entry([system, user, _summary("summary one"), first, second]),
            _compaction_entry([system, user, first], _summary("summary two")),
            # The second compaction preserves "first" again: it was already
            # trained in segment 0, though it was not generated in segment 2.
            _trajectory_entry(
                [system, user, _summary("summary two"), first, second, third]
            ),
        ],
    )

    rows = _rows_by_index(history)
    assert [mask for _, _, mask in _masks(rows[0])] == [0, 0, 1]
    assert [mask for _, _, mask in _masks(rows[2])] == [0, 0, 0, 0, 1]
    assert [mask for _, _, mask in _masks(rows[4])] == [0, 0, 0, 0, 0, 1]


def test_compaction_row_trains_only_the_summary_response():
    history = _history(
        [_message("system", "sys")],
        [
            _trajectory_entry([_message("system", "sys")]),
            _compaction_entry(
                [_message("system", "sys"), _message("user", "request")],
                _summary("the summary"),
            ),
            _trajectory_entry([_message("system", "sys"), _message("user", "next")]),
        ],
    )

    rows = _rows_by_index(history)
    assert _masks(rows[1]) == [
        ("system", "sys", 0),
        ("user", "request", 0),
        ("assistant", "the summary", 1),
    ]
